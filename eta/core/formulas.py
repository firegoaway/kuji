"""Формульные частоты (сессия 9, Задача 4): декларативные спецификации
в БД + жестко зафиксированные вычислители по идентификатору формулы.

Пилот – молниезащита (ГОСТ 12.1.004-91, прил. 3, п. 3.1.3;
СО 153-34.21.122-2003, табл. 2.2):
  N_у.м = (S + 6H)·(L + 6H)·n_у·10⁻⁶   – ожидаемое число ударов в год
                                        (S, L – размеры в плане, м;
                                         H – наибольшая высота, м;
                                         n_у – плотность ударов,
                                         км⁻²·год⁻¹);
  Q_пораж = N_у.м · (1 − η)            – с защитой уровня I–IV;
  без защиты η = 0 → Q = N_у.м.

Единицы (ответ пользователя 17): n_у – км⁻²·год⁻¹, поэтому 6 «напрямую»
в Q (год⁻¹) не подставляется – обязательно умножение на площадь удара
в км²: либо размеры объекта (пересчёт ·10⁻⁶), либо F_тер территории
(км²; поле «Площадь ударов молнии» с переключателем м² → км²).

Хранение: q_spec узла-причины =
  {"freq_mode": "formula", "formula": "<id>", "vars": {...}}.
Обратная совместимость: неизвестный идентификатор → запасное значение
q_init (старые файлы/БД).
"""

from __future__ import annotations

# надёжность защиты η по уровню (СО 153-34.21.122-2003, табл. 2.2);
# «нет» – объект без молниезащиты (Q = N_у.м)
LIGHTNING_ETA = {"I": 0.98, "II": 0.95, "III": 0.90, "IV": 0.80}

# переменные-перемножители по умолчанию (предзаполнение формы узла)
LIGHTNING_DEFAULTS = {"S": 100.0, "L": 100.0, "H": 20.0, "n_y": 6.0,
                      "prot": "II"}
# режим «территория»: вместо размеров – площадь ударов F_тер (км²)
LIGHTNING_DEFAULTS_AREA = {"F_km2": 0.05, "n_y": 6.0, "prot": "II"}


def lightning_eta(prot: str) -> float:
    """η по уровню защиты; «нет»/неизвестный → 0 (без защиты)."""
    return LIGHTNING_ETA.get(str(prot), 0.0)


def lightning_q(vars_: dict) -> float:
    """Q_пораж, год⁻¹: размеры объекта ИЛИ площадь ударов F_тер (км²).

    vars_: {S, L, H, n_y, prot} (м, м, м, км⁻²·год⁻¹, I–IV|нет) или
    {F_km2, n_y, prot} – площадь территории в км²."""
    v = dict(vars_ or {})
    n_y = float(v.get("n_y", 6.0))
    eta = lightning_eta(v.get("prot", "II"))
    if v.get("F_km2") is not None:
        n_um = float(v["F_km2"]) * n_y          # км² · км⁻²·год⁻¹ = год⁻¹
    else:
        s = float(v.get("S", 100.0))
        l = float(v.get("L", 100.0))
        h = float(v.get("H", 20.0))
        n_um = (s + 6.0 * h) * (l + 6.0 * h) * 1e-6 * n_y
    return n_um * (1.0 - eta)


# реестр вычислителей: идентификатор формулы -> функция(vars) -> float
_FORMULAS = {"lightning": lightning_q}


def formula_ids() -> list[str]:
    return sorted(_FORMULAS)


def compute_formula(formula_id: str, vars_: dict) -> float | None:
    """Вычислить формулу; None – неизвестный идентификатор (запасной
    путь: q_init)."""
    fn = _FORMULAS.get(formula_id)
    if fn is None:
        return None
    try:
        return float(fn(vars_ or {}))
    except (TypeError, ValueError):
        return None
