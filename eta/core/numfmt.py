# -*- coding: utf-8 -*-
"""Единая точка числовой типографики (Задача 7, сессия 14).

fmt_q   – инженерная запись частоты «3,24·10⁻⁶» (запятая, юникод-степени);
fmt_num – число для формул/значений: как %g, но запятая в мантиссе и
          инженерная запись там, где %g уходит в экспоненту («9e-05»
          пользователю больше не показывается нигде);
parse_eng – разбор ввода: экспоненциальная запись (1e-6, 1,02e10) И
          каретка (1^-6, 1,02^10), где m^e = m×10^e (LOCKED: каретка –
          «умножить на 10 в степени», НЕ возведение в степень).

Модуль стоит НИЖЕ model/layout (те импортируют его), поэтому не тянет
ни Qt, ни UI – единый источник для ядра и интерфейса, вилок нет.
"""

from __future__ import annotations

_SUP = {"0": "⁰", "1": "¹", "2": "²", "3": "³", "4": "⁴",
        "5": "⁵", "6": "⁶", "7": "⁷", "8": "⁸", "9": "⁹", "-": "⁻"}
_SUB = {"0": "₀", "1": "₁", "2": "₂", "3": "₃", "4": "₄",
        "5": "₅", "6": "₆", "7": "₇", "8": "₈", "9": "₉"}


def sup_digits(exp: int) -> str:
    """Юникод-надстрочники десятичной степени (минус → ⁻)."""
    return "".join(_SUP.get(ch, ch) for ch in str(exp))


def sub_digits(v: int) -> str:
    """Задача 4 (сессия 15): юникод-ПОДстрочники номера (индекс
    сценария Q_j); работает в плоском тексте (ячейки матрицы, PDF)."""
    return "".join(_SUB.get(ch, ch) for ch in str(int(v)))


def q_label(j: int) -> str:
    """«Q₂» – номер сценария подстрочником (плоский текст, без HTML;
    для формул матрицы и PDF-отчета)."""
    return f"Q{sub_digits(j)}"


def fmt_q(v: float) -> str:
    """Компактная инженерная запись частоты (напр. 2,30·10⁻⁵); 0 → «0»."""
    v = float(v)
    if v == 0:
        return "0"
    import math
    e = math.floor(math.log10(abs(v)))
    m = v / 10 ** e
    mant = f"{m:.2f}".rstrip("0").rstrip(".")
    return mant.replace(".", ",") + f"·10{sup_digits(e)}"


def fmt_num(v: float) -> str:
    """Число для отображения пользователю (формулы, значения, матрица):

    значение %g без экспоненты – как есть, но с запятой («0,05»,
    «1200», «2960,77»); значение %g с экспонентой («9e-05») –
    инженерная запись «9·10⁻⁵». Никогда не возвращает «e-notation»."""
    v = float(v)
    if v == 0:
        return "0"
    s = f"{v:g}"
    if "e" in s or "E" in s:
        return fmt_q(v)
    return s.replace(".", ",")


def parse_eng(text: str) -> float | None:
    """Разбор числового ввода. Принимает:

    * экспоненциальную запись: «1e-6», «1,02e10», «2.52e-12»;
    * каретку: «1^-6», «1,02^10», «2,52^-12» – m^e означает m×10^e;
    * произведение с десяткой: «6,2·10^-4», «6.2×10^-4», «6.2*10^-4».

    Запятая или точка в мантиссе. Некорректный ввод → None."""
    t = str(text).strip().replace(" ", "").replace(",", ".")
    if not t:
        return None
    for mult in ("·10^", "×10^", "*10^"):
        t = t.replace(mult, "e")
    if "^" in t:
        mant, sep, exp = t.partition("^")
        if not sep or not mant or not exp:
            return None
        try:
            m = float(mant)
            e = int(exp)
        except ValueError:
            return None
        t = f"{m}e{e}"
    try:
        v = float(t)
    except ValueError:
        return None
    return v if v == v else None          # NaN -> None
